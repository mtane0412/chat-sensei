/**
 * Twitch チャットの bot 向けコマンド(`!chimkin`、`!uptime` など)を判定する純関数。
 *
 * コマンドは視聴者が bot に向けて打つ文字列であり、翻訳や注目の表現の抽出の対象ではない。
 * LLM に渡すと `!chimkin` が `！ちむきん` のように音訳されるため、翻訳列・Pick up 列は
 * この判定で LLM を呼ばずに原文のまま確定させる(issue #35)。
 */

/**
 * 発言がチャットコマンドかを判定する。
 *
 * - 先頭の空白を除いて半角の `!` で始まり、その直後に空白以外の文字が続くものをコマンドとみなす
 * - `!chimkin please` のように引数付きでも発言全体をコマンド扱いにする(Twitch の bot コマンドの慣習)
 * - `!` だけ・`!!!` のような感嘆符のみの発言や、全角の `！` で始まる発言はコマンドではない
 */
export function isChatCommandMessage(text: string): boolean {
  return /^\s*![^\s!]/.test(text);
}
